export function getStatsForEnv(envId: string): InstructionStatsDto {
  const envInstructions = mockInstructions.filter(
    (i) => i.environment_id === envId
  );
  return computeStats(envInstructions);
}

function computeStats(instructions: InstructionDto[]): InstructionStatsDto {
  const now = new Date();
  return {
    total: instructions.length,
    open: instructions.filter((i) => i.status === 'open').length,
    in_progress: instructions.filter((i) => i.status === 'in_progress').length,
    completed: instructions.filter((i) => i.status === 'completed').length,
    archived: instructions.filter((i) => i.status === 'archived').length,
    overdue: instructions.filter(
      (i) =>
        i.due_date &&
        new Date(i.due_date) < now &&
        i.status !== 'completed' &&
        i.status !== 'archived'
    ).length,
    urgent: instructions.filter((i) => i.priority === 'urgent').length,
    due_soon: instructions.filter((i) => {
      if (!i.due_date || i.status === 'completed' || i.status === 'archived')
        return false;
      const due = new Date(i.due_date);
      const diffDays =
        (due.getTime() - now.getTime()) / (1000 * 60 * 60 * 24);
      return diffDays >= 0 && diffDays <= 7;
    }).length,
  };
}

